import {chromium} from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const base=process.env.HUNTMAPS_URL, out=process.env.HUNTMAPS_SCREENSHOTS;
if(!base||!out)throw Error('Run through ./gui/check');
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.HUNTMAPS_BROWSER||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
try {
 const page=await browser.newPage({viewport:{width:1500,height:1050}}), errors=[], requests=[];
 await page.addInitScript(()=>localStorage.setItem('huntmaps-online-imagery','off'));
 // No request interception: Playwright routing disables HTTP caching.
 const cdp=await page.context().newCDPSession(page);
 await cdp.send('Network.enable');
 const requestUrls=new Map(), cachedRequests=new Set();
 cdp.on('Network.requestWillBeSent',e=>requestUrls.set(e.requestId,e.request.url));
 cdp.on('Network.requestServedFromCache',e=>cachedRequests.add(e.requestId));
 cdp.on('Network.responseReceived',e=>{
   requestUrls.set(e.requestId,e.response.url);
   if(e.response.fromDiskCache||e.response.fromPrefetchCache)cachedRequests.add(e.requestId);
 });
 const coverageHits=(point='')=>[...cachedRequests].filter(id=>requestUrls.get(id)?.includes('/runs/search-fixture/')&&requestUrls.get(id)?.includes('/visible/'+(point ? point+'/' : ''))).length;
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.url().includes('/visible/'))requests.push({url:r.url(),background:r.headers()['x-huntmaps-prefetch']==='true'})});
 await page.goto(base);
 const began=Date.now();
 await page.getByLabel('Run selector').selectOption('search-fixture');
 const run=await (await page.request.get(base+'/api/runs/search-fixture')).json();
 const [first,second]=run.recommendation_ids;
 const ready=id=>page.locator('.coverage-status').filter({hasText:'Coverage ready · '+id}).waitFor({timeout:60000});
 await ready(first);
 const firstMs=Date.now()-began;
 assert.equal(await page.getByLabel('Coverage batch size').inputValue(),'10');
 await page.getByRole('button',{name:'Prepare coverage',exact:true}).click();
 const batchStarted=Date.now();
 await page.locator('.coverage-preparation[data-phase="preparing"]').waitFor({timeout:60000});
 await page.screenshot({path:out+'/coverage-preparation-desktop.png',fullPage:false});
 await page.locator('.coverage-preparation[data-phase="ready"]').waitFor({timeout:120000});
 const batchMs=Date.now()-batchStarted;
 const warmed=requests.filter(r=>r.background);
 assert.ok(warmed.length>0);
 assert.ok(new Set(warmed.map(r=>r.url.split('/visible/')[1].split('/')[0])).size<=run.candidates.length);
 const firstZoom=new URL(requests.find(r=>!r.background&&r.url.includes('/'+first+'/')).url).pathname.split('/visible/')[1].split('/')[1];
 assert.ok(warmed.some(r=>r.url.includes('/'+firstZoom+'/')),'Prefetch includes current raster zoom plus overview and neighboring zooms');
 const beforePrefetched=coverageHits(second);
 const secondStarted=Date.now();
 await page.getByLabel('Select '+second,{exact:true}).click(); await ready(second);
 const prefetchedMs=Date.now()-secondStarted;
 assert.ok(coverageHits(second)>beforePrefetched,'Selecting a prepared setup must reuse HTTP-cached coverage tiles');
 const before=requests.filter(r=>!r.background&&r.url.includes('/'+first+'/')).length;
 const returnStarted=Date.now();
 await page.getByLabel('Select '+first,{exact:true}).click(); await ready(first);
 const returnMs=Date.now()-returnStarted;
 const after=requests.filter(r=>!r.background&&r.url.includes('/'+first+'/')).length;
 assert.equal(after,before,'Returning to the same map view must reuse retained source tiles');
 const cache=()=>page.evaluate(()=>JSON.parse(document.querySelector('.map').dataset.coverageCache||'[]'));
 assert.ok((await cache()).length<=8);
 const beforeReload=coverageHits(first);
 await page.reload(); await page.getByLabel('Run selector').selectOption('search-fixture'); await ready(first);
 assert.ok(coverageHits(first)>beforeReload,'Reload must reuse the browser HTTP cache');
 await page.getByLabel('Select '+second,{exact:true}).click(); await ready(second);
 await page.locator('[data-tour="setup-'+second+'"]').getByRole('button',{name:'Dismiss',exact:true}).click();
 await page.getByLabel('Select '+first,{exact:true}).click(); await ready(first);
 await page.waitForFunction(id=>!JSON.parse(document.querySelector('.map').dataset.coverageCache||'[]').some(k=>k.startsWith('raster-visible-'+id+'-')),second);
 await page.getByLabel('Saved neighborhood').selectOption('dismissed');
 await page.locator('[data-tour="setup-'+second+'"]').getByRole('button',{name:'Restore',exact:true}).click();
 await page.getByLabel('Saved neighborhood').selectOption('recommended');
 await page.getByLabel('Select '+second,{exact:true}).click(); await ready(second);
 await page.getByLabel('Saved neighborhood').selectOption('all');
 for (const p of run.candidates.slice(0,10)) {
   await page.getByLabel('Select '+p.id,{exact:true}).click(); await ready(p.id);
   assert.ok((await cache()).length<=8,'Coverage source retention must remain bounded');
 }
 await page.getByLabel('Run selector').selectOption('workflow-fixture');
 // Find opens the leading recommendation/coverage setup; the saved approach
 // review focus is restored only when entering Approach.
 const workflowRun=await (await page.request.get(base+'/api/runs/workflow-fixture')).json();
 const workflowFirst=workflowRun.recommendation_ids[0]||[...workflowRun.candidates].sort((a,b)=>(b.metrics.raw_km2||0)-(a.metrics.raw_km2||0))[0].id;
 await ready(workflowFirst);
 assert.equal(await page.getByLabel('Select '+workflowFirst,{exact:true}).getAttribute('aria-pressed'),'true','Changing runs must select the new run’s coverage leader');
 assert.ok(requests.some(r=>!r.background&&r.url.includes('/runs/workflow-fixture/')&&r.url.includes('/visible/'+workflowFirst+'/')),'New-run selection must request its own coverage');
 assert.ok((await cache()).length>0);
 assert.ok((await cache()).every(key=>!key.includes('-search-fixture-')),'Changing runs must clear the old browser sources');
 const review=await (await page.request.get(base+'/api/runs/workflow-fixture/approach-review')).json();
 assert.equal(review.active_point,'A0001');
 const nav=page.getByRole('navigation',{name:'Scouting workflow'});
 await nav.getByRole('button',{name:/Approach.*selected/}).click();
 await ready(review.active_point);
 await page.getByRole('button',{name:'← Shortlist',exact:true}).click();
 assert.equal(await page.getByLabel('Select '+review.active_point,{exact:true}).getAttribute('aria-pressed'),'true','Approach must restore the saved review focus');
 await nav.getByRole('button',{name:/Find/}).click();
 await page.getByLabel('Run selector').selectOption('search-fixture'); await ready(first);
 assert.ok((await cache()).every(key=>!key.includes('-workflow-fixture-')),'Returning must clear the other run’s browser sources');
 await page.screenshot({path:out+'/coverage-cache-desktop.png',fullPage:true});
 await page.setViewportSize({width:900,height:900}); await ready(first);
 await page.screenshot({path:out+'/coverage-cache-900.png',fullPage:true});
 const heap=await cdp.send('Runtime.getHeapUsage');
 assert.deepEqual(errors,[]);
 fs.writeFileSync(out+'/results.json',JSON.stringify({firstMs,batchMs,prefetchedMs,returnMs,returnAdditionalTileRequests:after-before,httpCoverageCacheHits:coverageHits(),prefetchRequests:warmed.length,retainedSources:(await cache()).length,workflowFirst,restoredReviewFocus:review.active_point,heap,errors},null,2));
 console.log('Real coverage prefetch, source retention, reload HTTP cache and dismiss/restore verified:',out);
} finally {await browser.close()}
