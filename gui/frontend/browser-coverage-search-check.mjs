import {chromium} from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
if(!process.env.HUNTMAPS_URL || !process.env.HUNTMAPS_SCREENSHOTS) throw Error('Run through ./gui/check');
const base=process.env.HUNTMAPS_URL,out=process.env.HUNTMAPS_SCREENSHOTS;
fs.mkdirSync(out,{recursive:true});
const browser=await chromium.launch({executablePath:process.env.HUNTMAPS_BROWSER||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1500,height:1050}}),errors=[],requests=[];
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(()=>localStorage.setItem('huntmaps-online-imagery','off'));
await page.route('**/*',r=>r.request().url().startsWith(base)||r.request().url().startsWith('blob:')?r.continue():r.abort());
let fail=false,slow=true;
await page.route(/\/(?:tiles\/visible|filtered-tiles)\//,async r=>{
 requests.push(r.request().url());
 if(slow) await new Promise(resolve=>setTimeout(resolve,600));
 if(fail) await r.fulfill({status:500,contentType:'text/plain',body:'Synthetic tile failure'}); else await r.continue();
});
try {
 await page.goto(base);
 const coverageStarted=Date.now();
 await page.getByLabel('Run selector').selectOption('search-fixture');
 await page.locator('.coverage-status').filter({hasText:'Loading additional coverage'}).waitFor();
 await page.locator('.coverage-loading[data-phase="loading"]').waitFor();
 assert.equal(await page.locator('.map-pane').getAttribute('aria-busy'),'true');
 await page.screenshot({path:out+'/01-loading-desktop.png',fullPage:true});
 await page.locator('.coverage-status').filter({hasText:'Coverage ready'}).waitFor({timeout:60000});
 const initialCoverageMs=Date.now()-coverageStarted;
 await page.locator('.coverage-loading').waitFor({state:'hidden'});
 const run=await (await page.request.get(base+'/api/runs/search-fixture')).json();
 assert.equal(run.recommendation_ids.length,5);
 assert.equal(await page.getByLabel('Saved neighborhood').inputValue(),'recommended');
 assert.deepEqual((await page.locator('.candidate-select strong').allTextContents()).map(v=>v.trim()),run.recommendation_ids);
 const selected=run.recommendation_ids[0];
 const failedPoint=selected === "A0002" ? "A0001" : "A0002";
 const originalRequests=requests.filter(v=>v.includes('/'+selected+'/')).length;
 if(await page.locator('.layers').getAttribute('open')===null) await page.locator('.layers > summary').click();
 await page.getByLabel('Overlay opacity').fill('0.6');
 await page.locator('.coverage-status').filter({hasText:'Coverage ready'}).waitFor();
 assert.equal(requests.filter(v=>v.includes('/'+selected+'/')).length,originalRequests,'Opacity must reuse tiles');
 await page.getByLabel('Saved neighborhood').selectOption('all');
 slow=false; fail=true;
 await page.getByLabel('Select '+failedPoint,{exact:true}).click();
 await page.locator('.coverage-status').filter({hasText:'Coverage incomplete'}).waitFor({timeout:30000});
 await page.locator('.coverage-loading[data-phase="error"]').waitFor();
 await page.screenshot({path:out+'/02-incomplete-desktop.png',fullPage:true});
 assert.ok(requests.some(v=>v.includes('/filtered-tiles/')&&v.includes('/'+failedPoint+'/')),'Failure must reach the active filtered overlay');
 fail=false;
 await page.getByRole('button',{name:'Retry coverage',exact:true}).click();
 await page.locator('.coverage-status').filter({hasText:'Coverage ready · '+failedPoint}).waitFor({timeout:30000});
 // Rapid selection: delayed replies for A0003 must not replace A0004 status.
 slow=true;
 await page.getByLabel('Select A0003',{exact:true}).click();
 await page.getByLabel('Select A0004',{exact:true}).click();
 await page.locator('.coverage-status').filter({hasText:'Coverage ready · A0004'}).waitFor({timeout:30000});
 await page.getByLabel('Compare A0003',{exact:true}).check();
 await page.getByLabel('Compare A0004',{exact:true}).check();
 await page.getByRole('button',{name:'Exit compare',exact:true}).click();
 await page.locator('.coverage-status').filter({hasText:'Coverage ready · A0004'}).waitFor({timeout:30000});
 await page.setViewportSize({width:900,height:900});
 await page.locator('.coverage-status').filter({hasText:'Coverage ready · A0004'}).waitFor({timeout:30000});
 await page.screenshot({path:out+'/03-ready-900.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.setViewportSize({width:1500,height:1050});
 await page.getByRole('button',{name:'+ New area',exact:true}).click();
 const help = page.getByRole('button',{name:'Help: radius',exact:true});
 const tooltip = page.getByRole('tooltip').filter({hasText:'How far from each observer'});
 await help.hover(); await tooltip.waitFor({state:'visible'});
 await page.mouse.move(300,100); await tooltip.waitFor({state:'hidden'});
 await help.focus(); await tooltip.waitFor({state:'visible'});
 await page.keyboard.press('Escape'); await tooltip.waitFor({state:'hidden'});
 await help.click(); await tooltip.waitFor({state:'visible'});
 await page.getByLabel('New run name').click(); await tooltip.waitFor({state:'hidden'});
 await help.click(); await tooltip.waitFor({state:'visible'});
 await page.keyboard.press('Tab'); await tooltip.waitFor({state:'hidden'});
 await help.click(); await tooltip.waitFor({state:'visible'});
 await page.evaluate(()=>document.querySelector('.task-panel, .sidebar')?.dispatchEvent(new Event('scroll')));
 await page.evaluate(()=>window.dispatchEvent(new Event('scroll')));
 await tooltip.waitFor({state:'hidden'});
 await page.setViewportSize({width:900,height:900});
 await help.click(); await tooltip.waitFor({state:'visible'});
 await page.screenshot({path:out+'/05-help-900.png',fullPage:false});
 await page.keyboard.press('Escape'); await tooltip.waitFor({state:'hidden'});
 await page.setViewportSize({width:1500,height:1050});
 await page.getByLabel('Locations to test').fill('2000');
 assert.equal(await page.getByLabel('Locations to test').inputValue(),'2000');
 await page.getByLabel('Top spots to recommend').fill('12');
 await page.getByText('Advanced settings',{exact:true}).click();
 await page.getByLabel('Locations to test').fill('5000');
 await page.getByLabel('Nearby cover radius').selectOption('60');
 await page.getByLabel('Preferred tree cover below').fill('15');
 await page.screenshot({path:out+'/04-search-options-desktop.png',fullPage:true});
 assert.equal(await page.getByLabel('Locations to test').inputValue(),'5000');
 const touchPage=await browser.newPage({viewport:{width:900,height:900},hasTouch:true});
 await touchPage.addInitScript(()=>localStorage.setItem('huntmaps-online-imagery','off'));
 await touchPage.route('**/*',r=>r.request().url().startsWith(base)||r.request().url().startsWith('blob:')?r.continue():r.abort());
 await touchPage.goto(base);
 await touchPage.getByRole('button',{name:'+ New area',exact:true}).click();
 await touchPage.getByRole('button',{name:'Help: radius',exact:true}).tap();
 const touchTooltip=touchPage.getByRole('tooltip').filter({hasText:'How far from each observer'});
 await touchTooltip.waitFor({state:'visible'});
 await touchPage.getByLabel('New run name').tap(); await touchTooltip.waitFor({state:'hidden'});
 await touchPage.close();
 assert.deepEqual(errors,[]);
 fs.writeFileSync(out+'/results.json',JSON.stringify({errors,initialCoverageMs,coverageRequests:requests.length,recommended:run.recommendation_ids},null,2));
 console.log('Coverage loading, failure/retry, stale selection, tile reuse, recommendations and search controls verified:',out);
} finally {await page.unrouteAll({behavior:'wait'});await browser.close()}
