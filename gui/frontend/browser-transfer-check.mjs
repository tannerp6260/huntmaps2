import { chromium } from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const base=process.env.HUNTMAPS_URL, out=process.env.HUNTMAPS_SCREENSHOTS;
if (!base || !out) throw Error('Run through ./gui/check');
const browser=await chromium.launch({executablePath:process.env.HUNTMAPS_BROWSER||'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1500,height:1050}}), errors=[];
const id='b'.repeat(32), plan={id,prepared:true,candidates:['A0001'],sources:[],estimated_new_bytes:3e9,already_received_bytes:1e9,download_cap_bytes:3600e6,errors:[],source_note:'Synthetic source plan; no actual transfer.',review_signature:'synthetic',download_time:{basis:'illustrative',minimum_s:300,maximum_s:3000},storage:{reserve_bytes:20*2**30,required_bytes:12*2**30,processing_estimate_uncertain:true,blocked:false,volumes:[{path:'isolated fixture',free_bytes:80*2**30}]}};
let progress={phase:'download',label:'Downloading reviewed sources',completed:1e9,total:3e9,updated:Date.now()/1000,bytes_per_s:2e6,remaining_s:1000};
let status='running', includeJob=false, stalled=false;
page.on('pageerror',e=>errors.push(e.message));
await page.addInitScript(id=>{localStorage.setItem('huntmaps-online-imagery','off');localStorage.setItem('huntmaps-first-person-plan:workflow-fixture',id)},id);
await page.route('**/*',r=>r.request().url().startsWith(base)||r.request().url().startsWith('blob:')?r.continue():r.abort());
await page.route(`**/api/first-person/plans/${id}`,r=>r.fulfill({json:plan}));
await page.route('**/api/jobs',async r=>{const response=await r.fetch();const jobs=await response.json();await r.fulfill({json:[...(includeJob ? [{id:'c'.repeat(32),plan:id,name:'Synthetic progress',kind:'first-person-prepare',status,stage:progress.label,elapsed_s:40,progress:{...progress,updated:Date.now()/1000-(stalled?30:0)}}] : []),...jobs]})});
try {
 await page.goto(base);
 await page.getByLabel('Run selector').selectOption('workflow-fixture');
 await page.getByLabel('Select A0001',{exact:true}).click();
 await page.getByRole('button',{name:'View',exact:true}).click();
 const section=page.locator('.fp-preparation');
 await section.evaluate(el=>el.open=true);
 await section.getByText(/Estimated download time:/).waitFor();
 assert.match(await section.innerText(),/5 min–50 min/);
 assert.equal(await section.getByRole('checkbox',{name:/Allow this plan/}).count(),0);
 assert.equal(await section.getByRole('button',{name:'Prepare views',exact:true}).isDisabled(),false);
 includeJob=true;
 const bar=section.getByRole('progressbar',{name:'Download progress'});
 await bar.waitFor({timeout:15000});
 await section.getByText(/2.0 MB\/s/).waitFor();
 assert.ok(Math.abs(Number(await bar.getAttribute('value'))-1/3)<.01);
 await section.getByText(/20 Mbps default/).waitFor();
 assert.equal(await section.getByLabel('Assumed speed (MB/s)').count(),0);
 await page.screenshot({path:out+'/01-download-progress-desktop.png',fullPage:true});
 stalled=true;
 progress={...progress,updated:Date.now()/1000-30};
 await section.getByText('Waiting for data…',{exact:false}).waitFor({timeout:15000});
 stalled=false;
 progress={phase:'processing',label:'Preparing scenes',completed:1,total:2,updated:Date.now()/1000};
 await section.getByRole('progressbar',{name:'Task progress'}).waitFor({timeout:15000});
 assert.equal(Number(await section.getByRole('progressbar',{name:'Task progress'}).getAttribute('value')),.5);
 await page.setViewportSize({width:900,height:900});
 await page.screenshot({path:out+'/02-processing-progress-900.png',fullPage:true});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 progress={...progress,completed:2};
 await section.getByText('This stage is finished; the job is still running.',{exact:true}).waitFor({timeout:15000});
 progress={phase:'processing',label:'Validating outputs',completed:0,total:null,updated:Date.now()/1000};
 await page.waitForFunction(()=>document.querySelector('.fp-job progress')?.getAttribute('value')===null);
 plan.storage.blocked=true;
 await section.getByText(/Insufficient storage for this plan/).waitFor({timeout:15000});
 await page.reload();
 await page.getByLabel('Run selector').selectOption('workflow-fixture');
 await page.getByRole('button',{name:'View',exact:true}).click();
 await section.evaluate(el=>el.open=true);
 await section.getByText('Validating outputs',{exact:true}).waitFor();
 assert.deepEqual(errors,[]);
 fs.writeFileSync(out+'/results.json',JSON.stringify({errors,source:'synthetic progress only; no downloads',plan,progress},null,2));
 console.log('Download estimate, custom speed, progress, stall, reserve block, reload and 900px verified:',out);
} finally {await page.unrouteAll({behavior:'wait'});await browser.close()}
